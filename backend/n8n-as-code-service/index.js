// `pinData` here is a defensive pass-through, not the mechanism that
// actually pins anything on this n8n version — confirmed by direct
// experiment (Stage C4) that pinning only takes effect when persisted on
// the workflow definition at creation time (see runSandboxTest()'s create
// call). Kept here too in case a different n8n version does honor it.
async function n8nRunWorkflow(workflowId, workflowData, cookie, pinData = {}) {
  const n8nHost = process.env.N8N_HOST || 'http://localhost:5678';
  const nodes   = workflowData.nodes || [];
  
  // Safer trigger detection with priority order
  const TRIGGER_PRIORITY = [
    'n8n-nodes-base.manualTrigger',
    'n8n-nodes-base.scheduleTrigger',
    'n8n-nodes-base.webhook',
    'n8n-nodes-base.webhookTrigger',
  ];
  
  const trigger = TRIGGER_PRIORITY.reduce((found, type) =>
    found ?? nodes.find(n => n.type === type), null
  ) ?? nodes.find(n =>
    n.type?.toLowerCase().includes('trigger') &&
    !n.type?.toLowerCase().includes('error')
  ) ?? nodes[0];
  const res = await fetch(`${n8nHost}/rest/workflows/${workflowId}/run`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'Cookie': cookie },
    body: JSON.stringify({
      startNodes:      [trigger?.name || 'Manual Trigger'],
      destinationNode: '',
      runData:         null,
      pinData,
      workflowData:    workflowData,
    }),
  });
  if (!res.ok) throw new Error(`Run failed (${res.status}): ${await res.text()}`);
  const data = await res.json();
  const executionId = data?.data?.executionId ?? data?.executionId;
  if (!executionId) throw new Error(`No executionId in response: ${JSON.stringify(data)}`);
  return String(executionId);
}

async function n8nPollExecution(executionId, cookie) {
  const n8nHost  = process.env.N8N_HOST || 'http://localhost:5678';
  // Bumped from the original 30s (Stage B7) — a splitInBatches loop body now
  // actually executes for real in the sandbox (see CORE_SANDBOX_TYPES above),
  // and a multi-iteration loop can outrun a single 30s window even on a
  // small test batch.
  const deadline = Date.now() + 60000;
  while (Date.now() < deadline) {
    const res  = await fetch(`${n8nHost}/rest/executions/${executionId}`, {
      headers: { 'Cookie': cookie },
    });
    if (!res.ok) throw new Error(`Poll failed (${res.status})`);
    const exec = (await res.json())?.data;
    
    // Handle non-recoverable states
    if (exec?.status === 'waiting') {
      // Workflow paused at a Wait node — treat as partial success
      exec.finished = true;
    }
    if (exec?.status === 'crashed' || exec?.status === 'canceled') {
      // Non-recoverable — exit immediately with error
      throw new Error(`Execution ${exec.status}: workflow did not complete`);
    }
    
    if (exec?.finished === true) return exec;
    await new Promise(r => setTimeout(r, 1000));
  }
  throw new Error('Timeout: execution did not finish in 60 seconds');
}

function deserializeN8nRunData(dataStr) {
  if (!dataStr || typeof dataStr !== 'string') return null;
  try {
    const arr     = JSON.parse(dataStr);
    if (!Array.isArray(arr)) return null;
    const resolve = v => (typeof v === 'string' && /^\d+$/.test(v) && +v < arr.length)
      ? arr[+v] : v;
    const runDataMap = resolve(resolve(resolve(arr[0])?.resultData)?.runData);
    if (!runDataMap || typeof runDataMap !== 'object') return null;
    const out = {};
    for (const [name, ref] of Object.entries(runDataMap)) {
      const run    = resolve(ref);
      if (!run) continue;
      const status = resolve(run.executionStatus) || 'unknown';
      const errRaw = run.error ? resolve(run.error) : null;
      out[name] = {
        status,
        executionTime: run.executionTime ?? null,
        ...(errRaw && { error: typeof errRaw === 'string' ? errRaw : errRaw?.message ?? JSON.stringify(errRaw) }),
      };
    }
    return Object.keys(out).length ? out : null;
  } catch { return null; }
}

/**
 * True offline replay (Stage C4) — turns a captured fixture's raw execution
 * data into n8n's real `pinData` shape ({[nodeName]: [{json:{...}}, ...]})
 * so n8nRunWorkflow() can pin it onto matching node names: n8n then skips
 * re-executing those nodes for real and feeds their pinned output straight
 * downstream, instead of a fully-live run (Stage C3's "live re-run
 * comparison" already covers the fully-live case).
 *
 * Input is the PLAIN nested JSON shape n8n's public `/api/v1/executions/:id
 * ?includeData=true` returns (what frontend/avry-user-dashboard's
 * getExecutionDetailWithCreds() fetches and dashboard.workflow_fixtures
 * stores as run_data) — NOT the "flatted" reference-array format
 * deserializeN8nRunData() above parses, which is specific to n8n's internal
 * `/rest/executions/:id` polling response. Mirrors
 * frontend/avry-user-dashboard/lib/workflows/fixtureDiff.ts's
 * extractRunData() for the same reason: two different n8n endpoints, two
 * different serializations of the same underlying data.
 */
function buildPinDataFromFixtureRunData(fixtureRunData) {
  const pinData = {};
  if (!fixtureRunData || typeof fixtureRunData !== 'object') return pinData;

  const resultData = fixtureRunData.resultData || fixtureRunData;
  const runData     = resultData.runData || fixtureRunData.runData;
  if (!runData || typeof runData !== 'object') return pinData;

  for (const [nodeName, runs] of Object.entries(runData)) {
    if (!Array.isArray(runs) || runs.length === 0) continue;
    const lastRun = runs[runs.length - 1];
    const items   = lastRun?.data?.main?.[0];
    if (!Array.isArray(items) || items.length === 0) continue;
    // Items are already {json:{...}} envelopes — keep only `json` (and
    // `binary` if present), dropping execution-time metadata like
    // `pairedItem` indices that won't resolve against a different run.
    pinData[nodeName] = items.map((item) => ({
      json: item?.json ?? {},
      ...(item?.binary ? { binary: item.binary } : {}),
    }));
  }
  return pinData;
}

function stripCredentialsForSandbox(workflowDef) {
  // Deep clone
  const wf = JSON.parse(JSON.stringify(workflowDef));

  // Only core structural nodes execute for real in the sandbox — every
  // integration node (Slack, HubSpot, Zendesk, ...) is stubbed with a Set
  // node. The old approach blacklisted 8 specific credential node types;
  // any integration outside that list (e.g. HubSpot) ran for real, hit
  // "required parameter" / credential errors, and failed the whole test.
  // The sandbox validates flow structure, not third-party API calls.
  const CORE_SANDBOX_TYPES = new Set([
    'n8n-nodes-base.manualTrigger',
    'n8n-nodes-base.set',
    'n8n-nodes-base.if',
    'n8n-nodes-base.switch',
    'n8n-nodes-base.merge',
    'n8n-nodes-base.noOp',
    'n8n-nodes-base.filter',
    'n8n-nodes-base.code',
    // Real execution, not stubbed — loop bodies need to actually iterate for
    // a sandbox test to prove the flow's structure (Stage B7).
    'n8n-nodes-base.splitInBatches',
  ]);

  wf.nodes = wf.nodes.map(node => {
    // Remove any credential fields
    const stripped = { ...node };
    delete stripped.credentials;

    // Non-manual trigger nodes (webhook, app event triggers) cannot start a
    // manual /rest/.../run execution — n8n rejects the run with "No node to
    // start the workflow from could be found", which made EVERY sandbox test
    // fail. Swap them for a Manual Trigger, preserving id/name/position so
    // the workflow connections stay intact.
    const loweredType = (node.type || '').toLowerCase();
    const isNonManualTrigger =
      (loweredType.includes('trigger') && loweredType !== 'n8n-nodes-base.manualtrigger') ||
      loweredType === 'n8n-nodes-base.webhook' ||
      // Trigger types whose names lack the word "trigger" (static-fallback
      // node resolution emits these) — without this they get stubbed as Set
      // nodes and the workflow has no start node at all.
      loweredType === 'n8n-nodes-base.cron' ||
      loweredType === 'n8n-nodes-base.interval';
    if (isNonManualTrigger) {
      return {
        id:          stripped.id,
        name:        stripped.name,
        type:        'n8n-nodes-base.manualTrigger',
        typeVersion: 1,
        position:    stripped.position,
        parameters:  {},
      };
    }

    // A Code node whose JavaScript/Python was written by the configurator is NOT
    // executed on the production n8n: model-authored code must never run
    // unreviewed (it also assumes data shapes the stubbed upstream nodes lack and
    // could hang the run). It is stubbed like any integration node.
    const isGeneratedCode = stripped.type === 'n8n-nodes-base.code' && stripped.notes === AETHER_CONFIGURED_NOTE;

    // Any non-core node is swapped to a harmless Set node that proves the
    // logic flow works without credential/parameter errors
    if (isGeneratedCode || !CORE_SANDBOX_TYPES.has(stripped.type)) {
      return {
        id:          stripped.id,
        name:        stripped.name,
        type:        'n8n-nodes-base.set',
        typeVersion: 3.4,
        position:    stripped.position,
        parameters: {
          mode: 'manual',
          assignments: {
            assignments: [{
              id:    '1',
              name:  'sandbox_note',
              value: `[SANDBOX] ${node.name} — requires credential in production`,
              type:  'string',
            }]
          },
        },
      };
    }

    return stripped;
  });

  // Safety net for the case the swap loop above can't handle: a workflow
  // with NO trigger-type node at all (none of its nodes matched the
  // trigger-detection above, so nothing got converted to manualTrigger).
  // Without this, n8nRunWorkflow()'s trigger search falls through every
  // priority tier and starts from an arbitrary non-trigger node by name —
  // n8n's /run endpoint rejects that with "No node to start the workflow
  // from could be found" regardless of retries, since the real problem is
  // structural (no valid entry point), not transient.
  const hasTriggerNode = wf.nodes.some(n => n.type === 'n8n-nodes-base.manualTrigger');
  if (!hasTriggerNode && wf.nodes.length > 0) {
    const connections = wf.connections || {};
    const targetNames = new Set();
    for (const outputs of Object.values(connections)) {
      for (const branches of Object.values(outputs || {})) {
        for (const branch of branches || []) {
          for (const conn of branch || []) {
            if (conn && conn.node) targetNames.add(conn.node);
          }
        }
      }
    }
    // Prefer a node nothing else points to (the real graph root); fall
    // back to the first node in the list if every node has an inbound edge
    // (e.g. a cycle) or there's exactly one node.
    const entryNode = wf.nodes.find(n => !targetNames.has(n.name)) || wf.nodes[0];
    const injectedTrigger = {
      id:          crypto.randomUUID(),
      name:        'Sandbox Trigger',
      type:        'n8n-nodes-base.manualTrigger',
      typeVersion: 1,
      position:    [
        (entryNode.position?.[0] ?? 0) - 240,
        entryNode.position?.[1] ?? 0,
      ],
      parameters:  {},
    };
    wf.nodes = [injectedTrigger, ...wf.nodes];
    wf.connections = {
      ...connections,
      [injectedTrigger.name]: {
        main: [[{ node: entryNode.name, type: 'main', index: 0 }]],
      },
    };
    console.log(`[sandbox] No trigger node found in generated workflow — injected '${injectedTrigger.name}' -> '${entryNode.name}'`);
  }

  return wf;
}

async function runSandboxTest(workflowDefinition, pinData = {}) {
  const n8nHost = process.env.N8N_HOST    || 'http://localhost:5678';
  const apiKey  = process.env.N8N_API_KEY || '';
  const logs    = [];
  let   wfId    = null;
  const log     = m => { logs.push(m); console.log(`[sandbox] ${m}`); };
  const isReplay = Object.keys(pinData).length > 0;
  if (isReplay) log(`Offline replay: pinning ${Object.keys(pinData).length} node(s) from fixture data`);

  try {
    log('Creating sandbox workflow...');
    // Strip credentials so n8n can execute logic without credential errors
    // Credential validation is done separately via /drafts/bind-credentials
    const sandboxWorkflow = stripCredentialsForSandbox(workflowDefinition);
    log(`Stripped credentials from ${sandboxWorkflow.nodes.length} nodes for sandbox`);

    // -- Deterministic webhook trigger support (2026-08-25) --------------
    // n8n cannot start an execution from a Webhook trigger without a real
    // inbound HTTP call ("No node to start the workflow from could be
    // found"). Auto-pin a deterministic sample payload on the webhook
    // trigger so real_execution stays possible in sandbox tests. Explicit
    // fixture replay pinData always wins over the generated sample.
    const effectivePin = { ...pinData };
    if (!Object.keys(effectivePin).length) {
      const trig = sandboxWorkflow.nodes.find(n => String(n.type || '').includes('webhook'));
      if (trig) {
        const wfStep = Array.isArray(workflowDefinition?.steps)
          ? workflowDefinition.steps.find(st => st.nodeType && String(st.nodeType).includes('webhook'))
          : null;
        const cfgSample = wfStep?.parameters?.sampleBody;
        const sampleBody = (cfgSample && typeof cfgSample === 'object') ? cfgSample : {
          name: 'Sample Lead',
          email: 'sample@example.com',
          message: 'Deterministic sandbox payload',
        };
        effectivePin[trig.name] = [{ json: { headers: {}, params: {}, query: {}, body: sampleBody } }];
        log(`Auto-pinned webhook trigger "${trig.name}" with deterministic sample payload`);
      }
    }
    const hasPin = Object.keys(effectivePin).length > 0;
    const cr = await fetch(`${n8nHost}/api/v1/workflows`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'X-N8N-API-KEY': apiKey },
      body: JSON.stringify({
        ...sandboxWorkflow,
        settings: { ...(sandboxWorkflow.settings ?? {}), executionOrder: 'v1' },
        // True offline replay (Stage C4) — confirmed by direct experiment
        // against this VPS's real n8n that pinData ONLY takes effect when
        // persisted on the workflow definition itself (this create call).
        // Passing it as a parameter to /rest/workflows/:id/run (what
        // n8nRunWorkflow() below still does, harmlessly) is a no-op on this
        // n8n version — the plan's original description of that hook was
        // wrong about WHERE pinData needs to go, not whether the mechanism
        // exists at all.
        ...(hasPin ? { pinData: effectivePin } : {}),
      }),
    });
    if (!cr.ok) throw new Error(`Create failed (${cr.status}): ${await cr.text()}`);
    wfId = String((await cr.json())?.id ?? '');
    if (!wfId) throw new Error('No workflow ID returned from create');
    log(`Created: ${wfId}`);

    log('Logging in to n8n...');
    const cookie = await n8nLogin();
    log('Login OK');

    log('Fetching full workflow data (required for /run)...');
    const wfData = await n8nFetchWorkflow(wfId);
    log(`Fetched: ${wfData.nodes?.length} nodes`);

    // Pinned node names come from whatever workflow the fixture was captured
    // against — matched here purely by name (same convention fixtureDiff.ts
    // uses), so warn (don't fail) when a pinned name doesn't exist in THIS
    // workflow, e.g. after a step was renamed since the fixture was captured.
    if (hasPin) {
      const liveNodeNames = new Set((wfData.nodes || []).map(n => n.name));
      const unmatched = Object.keys(effectivePin).filter(name => !liveNodeNames.has(name));
      if (unmatched.length) log(`WARNING: fixture has data for node(s) not present in this workflow: ${unmatched.join(', ')}`);
    }

    log('Triggering execution...');
    const execId = await n8nRunWorkflow(wfId, wfData, cookie, effectivePin);
    log(`Execution started: ${execId}`);

    log('Waiting for result (max 30s)...');
    const exec = await n8nPollExecution(execId, cookie);
    log(`Finished: status=${exec.status}`);

    const runMap      = deserializeN8nRunData(exec?.data);
    const nodeResults = runMap
      ? Object.entries(runMap).map(([name, info]) => {
          // If node-level status is unknown, trust overall exec status
          const nodeStatus = (info.status && info.status !== 'unknown')
            ? (info.status === 'success' ? 'success' : 'error')
            : (exec.status === 'success' ? 'success' : 'error');
          return {
            nodeId: name, nodeName: name,
            status: nodeStatus,
            executionTime: info.executionTime ?? null,
            ...(info.error && { error: info.error }),
          };
        })
      : (exec?.workflowData?.nodes || []).map(n => ({
          nodeId: n.id, nodeName: n.name,
          status: exec.status === 'success' ? 'success' : 'error',
        }));

    nodeResults.forEach(n =>
      log(`  ${n.status === 'success' ? 'OK' : 'FAIL'} "${n.nodeName}"${n.error ? ': ' + n.error : ''}`)
    );

    // Annotate nodes that were credential-stripped in sandbox
    const credentialNodeTypes = [
      'n8n-nodes-base.mySql',
      'n8n-nodes-base.postgres',
      'n8n-nodes-base.emailSend',
      'n8n-nodes-base.ssh',
      'n8n-nodes-base.ftp',
      'n8n-nodes-base.slack',
      'n8n-nodes-base.notion',
      'n8n-nodes-base.googleSheets',
    ];
    const strippedNodeNames = (workflowDefinition.nodes || [])
      .filter(n => credentialNodeTypes.includes(n.type))
      .map(n => n.name);
    const annotatedResults = nodeResults.map(n => ({
      ...n,
      ...(strippedNodeNames.includes(n.nodeName) && {
        sandboxNote: 'credential-stripped: logic tested, credential required in production'
      })
    }));

    // DELETE must happen AFTER polling
    log(`Deleting sandbox workflow ${wfId}...`);
    await fetch(`${n8nHost}/api/v1/workflows/${wfId}`, {
      method: 'DELETE', headers: { 'X-N8N-API-KEY': apiKey },
    });
    wfId = null;
    log('Deleted');

    const passed = exec.status === 'success';
    return {
      status:         passed ? 'passed' : 'failed',
      validationMode: isReplay ? 'offline_replay' : 'real_execution',
      ...(isReplay ? { pinnedNodes: Object.keys(pinData) } : {}),
      executionId:    execId,
      nodeResults:    annotatedResults,
      errors: annotatedResults
        .filter(n => n.status === 'error')
        .map(n => `"${n.nodeName}": ${n.error ?? 'execution failed'}`),
      logs,
    };

  } catch (err) {
    log(`ERROR: ${err.message}`);
    if (wfId) {
      try {
        await fetch(`${n8nHost}/api/v1/workflows/${wfId}`, {
          method: 'DELETE', headers: { 'X-N8N-API-KEY': apiKey },
        });
        log('Emergency cleanup done');
      } catch (e) { log(`Emergency cleanup failed: ${e.message}`); }
    }
    return {
      status: 'error', validationMode: isReplay ? 'offline_replay' : 'real_execution',
      nodeResults: [], errors: [err.message], logs,
    };
  }
}

