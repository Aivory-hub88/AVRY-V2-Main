app.post('/drafts/deploy', async (req, res) => {
  try {
    const { draft_id, activate = true } = req.body || {};
    if (!draft_id) return res.status(400).json({ error: true, message: 'draft_id is required' });

    const meta        = readMeta(draft_id);
    const workflowDef = buildRealN8nWorkflow({
      draftId: meta.draftId,
      intent:  meta.intent,
      steps:   meta.steps,
    });

    // Step 1: Get credential bindings
    const availableCreds        = await n8nFetchCredentials();
    const { bindings, missing } = buildCredentialBindings(workflowDef.nodes, availableCreds, meta.steps);

    if (missing.length > 0) {
      return res.status(400).json({
        error:   true,
        message: `Cannot deploy: ${missing.length} credential(s) missing`,
        missing,
      });
    }

    // Step 2: Inject credentials into workflow nodes
    const boundWorkflow = injectCredentialsIntoWorkflow(workflowDef, bindings);
    boundWorkflow.name  = meta.intent || `Aivory Workflow ${meta.draftId}`;
    boundWorkflow.settings = {
      ...(boundWorkflow.settings || {}),
      executionOrder: 'v1',
    };

    // Step 3: Deploy to n8n production
    const n8nHost = process.env.N8N_HOST    || 'http://localhost:5678';
    const apiKey  = process.env.N8N_API_KEY || '';

    const createRes = await fetch(`${n8nHost}/api/v1/workflows`, {
      method:  'POST',
      headers: { 'Content-Type': 'application/json', 'X-N8N-API-KEY': apiKey },
      body:    JSON.stringify(boundWorkflow),
    });

    if (!createRes.ok) {
      throw new Error(`Deploy failed (${createRes.status}): ${await createRes.text()}`);
    }

    const deployed   = await createRes.json();
    const workflowId = String(deployed?.id ?? '');
    if (!workflowId) throw new Error('Deploy succeeded but no workflow ID returned');

    // Step 4: Activate if requested
    let activated = false;
    if (activate) {
      const activateRes = await fetch(`${n8nHost}/api/v1/workflows/${workflowId}/activate`, {
        method:  'POST',
        headers: { 'X-N8N-API-KEY': apiKey },
      });
      activated = activateRes.ok;
    }

    // Step 5: Persist deploy info to meta
    meta.status           = 'deployed';
    meta.deployedWorkflow = {
      workflowId,
      activated,
      deployedAt: new Date().toISOString(),
      workflowUrl: `${n8nHost}/workflow/${workflowId}`,
    };
    meta.updatedAt = new Date().toISOString();
    writeMeta(draft_id, meta);

    return res.json({
      draft_id,
      workflowId,
      activated,
      workflowUrl: `${n8nHost}/workflow/${workflowId}`,
      boundCredentials: bindings.length,
      summary: activated
        ? `Workflow deployed and activated. Open: ${n8nHost}/workflow/${workflowId}`
        : `Workflow deployed (not activated). Open: ${n8nHost}/workflow/${workflowId}`,
    });
  } catch (error) {
    res.status(error.status || 500).json({ error: true, message: error.message });
  }
});

