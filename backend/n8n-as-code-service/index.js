function detectIntent(stepTitle, stepType, stepDescription) {
  const text = `${stepTitle} ${stepType} ${stepDescription || ''}`.toLowerCase();

  const PATTERNS = {
    rss:       /\brss\b|\bfeed\b/,
    gmail:     /gmail/,
    schedule:  /schedule|cron|daily|hourly|weekly|timer|interval|every\s+\d|jadwal|setiap|berkala|per\s*\d+\s*jam|tiap/,
    email:     /email|mail\b|smtp|inbox|send.*mail/,
    database:  /mysql|postgres|postgresql|sql\b|database|db\b|query|select|insert/,
    openai:    /openai|open\s*ai|\bgpt-?\d/,
    http:      /\bhttp\b|\bapi\b|request\b|fetch\b|call.*endpoint|rest\b|post.*url|get.*url/,
    ssh:       /\bssh\b|\bscp\b|\bexec\b|remote.*command|run.*command|shell\b/,
    ftp:       /ftp|sftp|file.*transfer|upload.*file|download.*file/,
    compress:  /compress|zip\b|tar\b|gzip|archive|unzip|extract/,
    cleanup:   /delete\b|remove\b|cleanup|clean.*up|purge\b|clear\b|truncate/,
    filter:    /condition|\bif\b|decision|\bcheck\b|\bfilter\b|branch/,
    transform: /transform|convert|format\b|parse\b|extract\b|set.*value|map.*data/,
    messaging: /slack|discord|telegram|whatsapp|\bsms\b|\bteams\b/,
    respond:   /\brespond\b|\breturn\b|send.*response|reply\b|webhook.*response/,
    webhook:   /webhook|trigger.*http|http.*trigger|on.*request/,
    ai:        /\bai\b|\bllm\b|analyze|generate\b|summarize|classify|\bgpt\b|zeroclaw/,
  };

  // stepType exact match first
  if (stepType && PATTERNS[stepType]) return stepType;

  // A step explicitly marked as a trigger MUST resolve to a trigger-shaped
  // node. Without this, the generic full-text loop below can misfire on an
  // unrelated word elsewhere in the title/description — e.g. a step titled
  // "Schedule Trigger" whose description happens to mention "Gmail" (the
  // app being polled, not the trigger mechanism) matched PATTERNS.gmail
  // before ever reaching PATTERNS.schedule, purely because `gmail` is
  // declared earlier than `schedule` in PATTERNS and Object.entries()
  // iterates in declaration order. That produced a plain Gmail node with
  // no trigger anywhere in the workflow — n8n then rejects every run with
  // "No node to start the workflow from could be found" (both the sandbox
  // test and the real /drafts/deploy path build through this same
  // function, so the bug silently broke both). Check only trigger-capable
  // categories first; fall back to a bare manual trigger if the text gives
  // no schedule/webhook cue at all.
  if (stepType === 'trigger') {
    if (PATTERNS.schedule.test(text)) return 'schedule';
    if (PATTERNS.webhook.test(text)) return 'webhook';
    return 'trigger';
  }

  // Pattern match on full text
  for (const [intent, pattern] of Object.entries(PATTERNS)) {
    if (pattern.test(text)) return intent;
  }

  // Fallback: first step = trigger, rest = transform
  return 'default';
}

const AETHER_CONFIGURED_NOTE = 'Configured by Aivory Aether from n8n node definitions.';

function buildRealN8nWorkflow({ draftId, intent, steps }) {
  const nodes      = [];
  const connections = {};
  const GRID_X     = 280;  // horizontal spacing between nodes
  const START_X    = 100;
  const START_Y    = 300;

  // If no steps or empty, fallback to manual trigger only
  if (!steps || steps.length === 0) {
    return {
      name: `Aivory Draft ${draftId}`,
      settings: {},
      nodes: [
        {
          id: 'ManualTrigger_1',
          name: 'Manual Trigger',
          type: 'n8n-nodes-base.manualTrigger',
          typeVersion: 1,
          position: [START_X, START_Y],
          parameters: {},
        },
      ],
      connections: {},
    };
  }

  // Intents whose node can return multiple items — when immediately followed
  // by an AI step, a Limit node goes in between so the agent runs once per
  // batch instead of once per item.
  const MULTI_ITEM_INTENTS = new Set(['rss', 'http', 'database']);

  // n8n-nodes-base.splitInBatches output convention — same as
  // frontend/avry-user-dashboard/lib/workflowConverter.ts's LOOP_DONE_OUTPUT/
  // LOOP_BODY_OUTPUT: output 0 fires once after all batches are done, output
  // 1 fires once per batch and is where the loop body connects. Confirmed
  // against this VPS's real n8n instance right after this file was deployed
  // (a trigger->loop->body->finish sandbox test executed end to end).
  const LOOP_DONE_OUTPUT = 0;
  const LOOP_BODY_OUTPUT = 1;

  // `branchIndex` selects which of the source's n8n outputs this connection
  // comes from — always 0 (the only output) for a plain node; only
  // condition/switch/loop primaries have more than one.
  const addConnection = (from, to, type = 'main', branchIndex = 0) => {
    if (!connections[from]) connections[from] = {};
    if (!connections[from][type]) connections[from][type] = [];
    while (connections[from][type].length <= branchIndex) connections[from][type].push([]);
    connections[from][type][branchIndex].push({ node: to, type, index: 0 });
  };

  // `nodeSeq` is a running counter across the WHOLE recursive walk (not just
  // one steps array) so node ids/positions stay unique once branches/loop
  // bodies are nested — mirrors the frontend's globalStepCounter.
  let nodeSeq = 0;

  function buildLoopNode(step) {
    const idx = nodeSeq++;
    const position = [START_X + (idx * GRID_X), START_Y];
    return {
      id: `node_${idx + 1}_loop`,
      name: step.title || `Step ${idx + 1}`,
      type: 'n8n-nodes-base.splitInBatches',
      typeVersion: 3,
      position,
      parameters: { batchSize: (step.loopConfig && step.loopConfig.batchSize) || 1, options: {} },
    };
  }

  function buildSwitchNode(step) {
    const idx = nodeSeq++;
    const position = [START_X + (idx * GRID_X), START_Y];
    return {
      id: `node_${idx + 1}_switch`,
      name: step.title || `Step ${idx + 1}`,
      type: 'n8n-nodes-base.switch',
      typeVersion: 3,
      position,
      parameters: {
        mode: 'rules',
        rules: {
          values: step.branches.map((b) => ({
            conditions: {
              options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
              conditions: [
                { leftValue: '={{ $json.response }}', rightValue: b.key, operator: { type: 'string', operation: 'equals' } },
              ],
              combinator: 'and',
            },
            renameOutput: true,
            outputKey: b.label || b.key,
          })),
        },
        options: { fallbackOutput: 'none' },
      },
    };
  }

  function buildConditionNode(step) {
    const idx = nodeSeq++;
    const position = [START_X + (idx * GRID_X), START_Y];
    // Plain if-node scaffold — 2 fixed outputs (true=0/false=1), matching
    // branches[0]/branches[1] by array position. Same placeholder condition
    // as NODE_TYPE_MAP.filter; the user fills in the real field later.
    return {
      id: `node_${idx + 1}_if`,
      name: step.title || `Step ${idx + 1}`,
      type: 'n8n-nodes-base.if',
      typeVersion: 2,
      position,
      parameters: { conditions: { options: {}, conditions: [] } },
    };
  }

  /**
   * Recursively convert a step array, wiring each step's primary node from
   * `entryNodeName`'s `entryBranchIndex`-th output (only meaningful for the
   * very first step in `stepList`). `entryNodeName` is `null` at the very
   * top level — this file never synthesizes a trigger node of its own, the
   * first step IS the trigger and gets no incoming connection, matching the
   * pre-existing (pre-branch/loop) behavior of this function. Returns the
   * tail node name a caller should continue its own chain from.
   */
  function convertSteps(stepList, entryNodeName, entryBranchIndex) {
    let prevNodeName    = entryNodeName;
    let prevBranchIndex = entryBranchIndex;
    let prevDetectedIntent = null;

    stepList.forEach((step, i) => {
      const hasBranches = !!(step.branches && step.branches.length);
      let primaryName;
      let detectedIntent = null;

      let connectFrom   = prevNodeName;
      let connectBranch = i === 0 ? prevBranchIndex : 0;

      if (hasBranches && step.type === 'switch') {
        const node = buildSwitchNode(step);
        nodes.push(node);
        if (connectFrom) addConnection(connectFrom, node.name, 'main', connectBranch);
        primaryName = node.name;
      } else if (hasBranches && step.type === 'loop') {
        const node = buildLoopNode(step);
        nodes.push(node);
        if (connectFrom) addConnection(connectFrom, node.name, 'main', connectBranch);
        primaryName = node.name;
      } else if (hasBranches) {
        const node = buildConditionNode(step);
        nodes.push(node);
        if (connectFrom) addConnection(connectFrom, node.name, 'main', connectBranch);
        primaryName = node.name;
      } else {
        // Use nodeType from step if provided (from ZeroClaw/n8n MCP inspection)
        // Fall back to detectIntent only if nodeType is not available
        let nodeConfig;
        if (step.nodeType) {
          nodeConfig = {
            type: step.nodeType,
            typeVersion: step.typeVersion || 1,
            parameters: step.parameters || {},
          };
          detectedIntent = 'direct';
        } else {
          detectedIntent = detectIntent(
            step.title || step.action || '',
            step.type  || '',
            step.description || ''
          );
          nodeConfig = NODE_TYPE_MAP[detectedIntent] || NODE_TYPE_MAP.default;
        }
        const idx = nodeSeq++;
        const nodeName = step.title || `Step ${idx + 1}`;
        const position = [START_X + (idx * GRID_X), START_Y];

        // AI steps deploy as a native AI Agent node + a linked Chat Model
        // sub-node (ai_languageModel connection) instead of a single generic
        // node — mirrors frontend/avry-user-dashboard's nodeMapper.ts.
        if (detectedIntent === 'ai' || detectedIntent === 'openai') {
          const isAnthropic = /claude|anthropic/i.test(`${step.title || ''} ${step.action || ''} ${step.description || ''}`);
          const modelNodeName = `${isAnthropic ? 'Anthropic' : 'OpenAI'} Chat Model${idx > 0 ? ` ${idx}` : ''}`;

          if (connectFrom && prevDetectedIntent && MULTI_ITEM_INTENTS.has(prevDetectedIntent)) {
            const limitName = `Limit ${idx}`;
            nodes.push({
              id: `node_${idx + 1}_limit`,
              name: limitName,
              type: 'n8n-nodes-base.limit',
              typeVersion: 1,
              position: [position[0] - 90, position[1]],
              parameters: { maxItems: 1 },
            });
            addConnection(connectFrom, limitName, 'main', connectBranch);
            connectFrom = limitName;
            connectBranch = 0;
          }

          nodes.push({
            id: `node_${idx + 1}_agent`,
            name: nodeName,
            type: '@n8n/n8n-nodes-langchain.agent',
            typeVersion: 1.7,
            position,
            parameters: {
              promptType: 'define',
              text: '={{ $json.response || $json.body || JSON.stringify($json) }}',
              options: { systemMessage: step.description || step.title || step.action || '' },
            },
          });
          nodes.push({
            id: `node_${idx + 1}_model`,
            name: modelNodeName,
            type: isAnthropic ? '@n8n/n8n-nodes-langchain.lmChatAnthropic' : '@n8n/n8n-nodes-langchain.lmChatOpenAi',
            typeVersion: 1,
            position: [position[0], position[1] + 200],
            parameters: {
              model: { value: isAnthropic ? 'claude-3-5-sonnet-20241022' : 'gpt-4o', mode: 'list' },
              options: {},
            },
          });
          addConnection(modelNodeName, nodeName, 'ai_languageModel');

          if (connectFrom) addConnection(connectFrom, nodeName, 'main', connectBranch);
          primaryName = nodeName;
        } else {
          const nodeId = `node_${idx + 1}_${idx}`;
          nodes.push({
            id:          nodeId,
            name:        nodeName,
            type:        nodeConfig.type,
            typeVersion: nodeConfig.typeVersion,
            position,
            parameters:  { ...nodeConfig.parameters },
            // Marker for nodes configured by the Aether node configurator (LLM +
            // n8n type definitions); the sandbox never executes generated code.
            ...(step.n8nInspection?.configured ? { notes: AETHER_CONFIGURED_NOTE } : {}),
          });

          if (connectFrom) addConnection(connectFrom, nodeName, 'main', connectBranch);
          primaryName = nodeName;
        }
      }

      prevNodeName    = primaryName;
      prevBranchIndex = 0;
      prevDetectedIntent = detectedIntent;

      if (hasBranches && step.type !== 'loop') {
        // Condition/switch — every branch's tail feeds into a shared join
        // node (n8n-nodes-base.noOp) before the outer chain resumes.
        const joinName = `${primaryName} · join`;
        nodes.push({
          id: `node_join_${nodeSeq++}`,
          name: joinName,
          type: 'n8n-nodes-base.noOp',
          typeVersion: 1,
          position: [START_X + (nodeSeq * GRID_X), START_Y + 260],
          parameters: {},
        });
        step.branches.forEach((branch, branchIdx) => {
          if (!branch.steps || !branch.steps.length) return; // unconnected output — no-op branch
          const branchTail = convertSteps(branch.steps, primaryName, branchIdx);
          addConnection(branchTail, joinName, 'main');
        });
        prevNodeName = joinName;
      } else if (hasBranches && step.type === 'loop') {
        // Loop body recursively converted off the "loop" output; its tail
        // wires back into the loop node itself (the cyclic back-edge n8n's
        // Split In Batches expects). The outer chain resumes from the loop
        // node's "done" output.
        const body = step.branches[0];
        if (body && body.steps && body.steps.length) {
          const bodyTail = convertSteps(body.steps, primaryName, LOOP_BODY_OUTPUT);
          addConnection(bodyTail, primaryName, 'main');
        }
        prevBranchIndex = LOOP_DONE_OUTPUT;
      }
    });

    return prevNodeName;
  }

  convertSteps(steps, null, 0);

  return {
    name:        intent || `Aivory Workflow ${draftId}`,
    settings:    {},
    nodes,
    connections,
  };
}

async function n8nApiRequest(method, apiPath, body) {
  const url = `${N8N_HOST}/api/v1${apiPath}`;
  const headers = { 'Content-Type': 'application/json' };
  if (N8N_API_KEY) headers['X-N8N-API-KEY'] = N8N_API_KEY;

  const response = await fetch(url, {
    method,
    headers,
    body: body ? JSON.stringify(body) : undefined,
  });

  const text = await response.text();
  if (!response.ok) {
    const error = new Error(text.trim() || `${method} ${apiPath} failed`);
    error.status = response.status;
    throw error;
  }

  try {
    return text ? JSON.parse(text) : null;
  } catch {
    return text;
  }
}

function readMeta(draftId) {
  const { metaPath } = draftPaths(draftId);
  if (!fs.existsSync(metaPath)) {
    const error = new Error('draft not found');
    error.status = 404;
    throw error;
  }
  return JSON.parse(fs.readFileSync(metaPath, 'utf8'));
}

function writeMeta(draftId, meta) {
  const { metaPath } = draftPaths(draftId);
  fs.writeFileSync(metaPath, JSON.stringify(meta, null, 2));
}

// Prefer a credential type n8n itself lists for the node: OAuth2 first, then API.
function pickCredentialType(types) {
  if (!Array.isArray(types) || types.length === 0) return undefined;
  return types.find((t) => /oauth2/i.test(t)) || types.find((t) => /api$/i.test(t)) || types[0];
}

// Requirement for a step whose node was configured from n8n's own type
// definitions (bridge nodeConfigurator): the credentials n8n lists for that
// node plus only the values the user really has to supply — no templates.
function requirementFromConfiguredNode(step) {
  const cfg = step.n8nInspection?.configured;
  if (!cfg || !step.nodeType) return undefined; // not configured -> legacy inference
  const displayName = step.n8nInspection?.selectedNode?.displayName
    || String(step.nodeType).split('.').pop().replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
  const credentialType = pickCredentialType(cfg.credentialTypes);
  const requiredFields = [];
  if (credentialType) {
    requiredFields.push({
      key: credentialType,
      label: `${displayName} account`,
      type: /oauth2/i.test(credentialType) ? 'oauth' : 'password',
    });
  }
  for (const item of Array.isArray(cfg.needsInput) ? cfg.needsInput : []) {
    requiredFields.push({ key: item.path || item.label, label: item.label, type: 'text' });
  }
  if (!credentialType && requiredFields.length === 0) return null; // fully configured, nothing to set up
  return {
    nodeId: step.id || String(step.title || displayName).toLowerCase().replace(/[^a-z0-9]+/g, '_'),
    nodeName: step.title || displayName,
    nodeType: step.nodeType,
    credentialType,
    requiredFields,
  };
}

function inferNodeRequirement(step) {
  // condition / switch / loop steps are logic, not integrations: their text often
  // mentions the apps used inside the branches ("...tell Slack"), which made the
  // keyword templates demand a Slack bot token for the condition itself.
  if (['condition', 'switch', 'loop'].includes(step.type)) return null;
  const fromConfigured = requirementFromConfiguredNode(step);
  if (fromConfigured !== undefined) return fromConfigured;
  const title = step.title || step.action || step.nodeName || step.id || 'Workflow Step';
  const description = step.description || step.output || '';
  const haystack = `${title} ${description}`.toLowerCase();
  const inspectedNode = step.n8nInspection?.selectedNode;

  const definitions = [
    {
      match: /(email|smtp|mail|newsletter)/,
      nodeName: 'Email Delivery',
      nodeType: 'n8n-nodes-base.emailSend',
      credentialType: 'smtpCredentials',
      requiredFields: [
        { key: 'host', label: 'SMTP Host', type: 'text', example: 'smtp.gmail.com' },
        { key: 'port', label: 'SMTP Port', type: 'text', example: '465' },
        { key: 'user', label: 'SMTP Username', type: 'text', example: 'automation@company.com' },
        { key: 'password', label: 'SMTP Password / App Password', type: 'password' },
      ],
    },
    {
      match: /(slack)/,
      nodeName: 'Slack',
      nodeType: 'n8n-nodes-base.slack',
      credentialType: 'slackApi',
      requiredFields: [{ key: 'botToken', label: 'Slack Bot Token', type: 'password' }],
    },
    {
      match: /(notion)/,
      nodeName: 'Notion',
      nodeType: 'n8n-nodes-base.notion',
      credentialType: 'notionApi',
      requiredFields: [{ key: 'apiKey', label: 'Notion Internal Integration Token', type: 'password' }],
    },
    {
      match: /(crm|hubspot|salesforce|pipedrive)/,
      nodeName: 'CRM',
      nodeType: 'n8n-nodes-base.httpRequest',
      credentialType: 'httpHeaderAuth',
      requiredFields: [
        { key: 'baseUrl', label: 'CRM Base URL', type: 'text', example: 'https://api.hubapi.com' },
        { key: 'apiKey', label: 'CRM API Key / Token', type: 'password' },
      ],
    },
    {
      match: /(sheet|spreadsheet|google sheet|sheets)/,
      nodeName: 'Google Sheets',
      nodeType: 'n8n-nodes-base.googleSheets',
      credentialType: 'googleSheetsOAuth2Api',
      requiredFields: [{ key: 'oauth', label: 'Google Sheets OAuth', type: 'oauth' }],
    },
    {
      match: /(http|api|webhook|rest)/,
      nodeName: 'HTTP Request',
      nodeType: 'n8n-nodes-base.httpRequest',
      credentialType: 'httpHeaderAuth',
      requiredFields: [
        { key: 'baseUrl', label: 'API Base URL', type: 'text', example: 'https://api.example.com' },
        { key: 'apiKey', label: 'API Key / Bearer Token', type: 'password' },
      ],
    },
  ];

  const matched = definitions.find((definition) => definition.match.test(haystack));
  if (!matched && inspectedNode && step.n8nInspection?.schema?.credentials) {
    return {
      nodeId: step.id || title.toLowerCase().replace(/[^a-z0-9]+/g, '_'),
      nodeName: inspectedNode.displayName || title,
      nodeType: inspectedNode.workflowNodeType || inspectedNode.nodeType || 'unknown',
      credentialType: step.n8nInspection?.schema?.credentials ? 'credential_required' : undefined,
      requiredFields: [],
    };
  }
  if (!matched) return null;

  return {
    nodeId: step.id || title.toLowerCase().replace(/[^a-z0-9]+/g, '_'),
    nodeName: matched.nodeName,
    nodeType: matched.nodeType,
    credentialType: matched.credentialType,
    requiredFields: matched.requiredFields,
  };
}

// Every step including those inside condition/switch/loop branches: a Slack
// alert inside an "if overdue" branch needs its credential like any other step.
function flattenSteps(steps, out = []) {
  for (const step of Array.isArray(steps) ? steps : []) {
    out.push(step);
    for (const branch of step.branches || []) flattenSteps(branch.steps, out);
  }
  return out;
}

function buildSetupReport(meta) {
  const nodeRequirements = flattenSteps(meta.steps).map(inferNodeRequirement).filter(Boolean);
  return {
    workflowId: meta.draftId,
    workflowName: meta.intent || 'Aivory Workflow Draft',
    readyToDeploy: nodeRequirements.length === 0,
    nodeRequirements,
    summary: nodeRequirements.length === 0
      ? 'No external credentials were inferred from the current draft.'
      : `This draft needs ${nodeRequirements.length} credential or configuration setup item(s) before activation.`,
  };
}

